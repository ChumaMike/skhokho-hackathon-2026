#!/usr/bin/env node
/**
 * Keeps the derived legal files in step with the markdown in docs/legal/:
 *
 *   1. src/lib/legal/generated/*.ts — the customer-facing texts as TypeScript
 *      string modules, so /terms and /privacy render the exact
 *      attorney-reviewed text without reading the filesystem at runtime
 *      (Vercel functions do not ship docs/).
 *   2. docs/legal/README.md — the register of every "[ATTORNEY: …]" and
 *      "[FILL IN: …]" marker across the drafts, with file and line, so
 *      counsel and the operator can work through them and nobody has to
 *      grep to know what is still open.
 *
 *   node scripts/legal/sync-legal-texts.mjs          # write
 *   node scripts/legal/sync-legal-texts.mjs --check  # exit 1 if out of date
 *
 * src/lib/legal/legal-texts.test.ts runs the same comparison, so a stale
 * generated file or register fails the unit suite rather than shipping old
 * text.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
const outDir = join(root, 'src', 'lib', 'legal', 'generated')
const legalDir = join(root, 'docs', 'legal')

/** key → [markdown source, generated module] — keep in step with LEGAL_DOCUMENTS. */
export const LEGAL_TEXT_FILES = {
  terms: ['docs/legal/terms-of-service.md', 'terms-of-service.ts'],
  privacy: ['docs/legal/privacy-notice.md', 'privacy-notice.ts'],
}

export function toModule(markdown) {
  const escaped = markdown.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')
  return `// GENERATED by scripts/legal/sync-legal-texts.mjs — do not edit. Edit the markdown in docs/legal/ and re-run the script.\nconst text = \`${escaped}\`\nexport default text\n`
}

/** Every [ATTORNEY: …] / [FILL IN: …] marker in a markdown string, with its 1-based line. */
export function extractMarkers(markdown) {
  const text = markdown.replace(/\r\n/g, '\n')
  const out = []
  const re = /\[(ATTORNEY|FILL IN):\s*([^\]]*)\]/g
  let m
  while ((m = re.exec(text))) {
    const line = text.slice(0, m.index).split('\n').length
    const point = m[2].replace(/\s+/g, ' ').trim()
    if (point === '…' || point === '...' || point === '') continue // the "how to read the markers" legend, not an open point
    out.push({ kind: m[1], line, text: point })
  }
  return out
}

function readmeTitle(markdown) {
  const m = markdown.match(/^#\s+(.+?)\s*$/m)
  return m ? m[1].trim() : null
}

function versionLine(markdown) {
  const m = markdown.match(/\*\*Version:\*\*\s*([^\s·]+)/)
  return m ? m[1] : null
}

const escapeCell = (s) => s.replace(/\|/g, '\\|')

export function buildReadme(files) {
  const lines = []
  lines.push('# docs/legal — register of open points')
  lines.push('')
  lines.push('GENERATED by `scripts/legal/sync-legal-texts.mjs` (`npm run legal:sync`) — do not edit by hand; `npm run legal:check` and the unit suite fail when this file is stale.')
  lines.push('')
  lines.push('Every document in this folder is a **DRAFT FOR ATTORNEY REVIEW**. None has been reviewed by counsel, none is in force, and the app says so wherever it shows one:')
  lines.push('')
  lines.push('- `/terms` and `/privacy` render the markdown with a "Draft for attorney review — not yet in force" badge while `draft` is true in `src/lib/legal/documents.ts`, and the version string itself (`v0.1-draft-…`) says draft.')
  lines.push('- the checkout and booking consent lines link to those pages and record the version shown; they make no claim that the text is final.')
  lines.push('- the storefront footer\'s ECTA s43 block shows the business\'s own details and links to `/terms` and `/privacy`; it carries no statement about the status of the platform texts.')
  lines.push('- the driver terms and driver privacy notice are not served by the app at all until `DRIVER_TERMS_*` / `DRIVER_PRIVACY_*` point at published documents.')
  lines.push('')
  lines.push('Two kinds of marker appear inline. **[ATTORNEY: …]** is a point counsel must decide or confirm. **[FILL IN: …]** is a fact Skhokho Laboratory ("Skhokho Labs") must supply before publication. Neither may remain in a published version.')
  lines.push('')
  let attorney = 0
  let fillIn = 0
  const perFile = []
  for (const file of files) {
    const md = readFileSync(join(legalDir, file), 'utf8')
    const markers = extractMarkers(md)
    const a = markers.filter((m) => m.kind === 'ATTORNEY').length
    const f = markers.length - a
    attorney += a
    fillIn += f
    perFile.push({ file, title: readmeTitle(md) ?? file, version: versionLine(md) ?? '—', markers, a, f })
  }
  lines.push('## Documents')
  lines.push('')
  lines.push('| File | Title | Version | ATTORNEY | FILL IN |')
  lines.push('|---|---|---|---|---|')
  for (const d of perFile) lines.push(`| \`${d.file}\` | ${escapeCell(d.title)} | ${d.version} | ${d.a} | ${d.f} |`)
  lines.push(`| **Total** | | | **${attorney}** | **${fillIn}** |`)
  lines.push('')
  lines.push('## Every marker, by file')
  lines.push('')
  for (const d of perFile) {
    lines.push(`### \`${d.file}\``)
    lines.push('')
    if (!d.markers.length) {
      lines.push('_No markers._')
      lines.push('')
      continue
    }
    lines.push('| Line | Kind | Point |')
    lines.push('|---|---|---|')
    for (const m of d.markers) lines.push(`| ${m.line} | ${m.kind} | ${escapeCell(m.text)} |`)
    lines.push('')
  }
  return lines.join('\n')
}

const check = process.argv.includes('--check')
let stale = 0

function sync(target, expected, label) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : null
  if (current === expected) return
  stale += 1
  if (check) {
    console.error(`[legal] ${label} is out of date`)
  } else {
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, expected)
    console.log(`[legal] wrote ${label}`)
  }
}

for (const [key, [source, generated]] of Object.entries(LEGAL_TEXT_FILES)) {
  const markdown = readFileSync(join(root, source), 'utf8')
  sync(join(outDir, generated), toModule(markdown), `${generated} from ${source} (${key})`)
}

const drafts = readdirSync(legalDir)
  .filter((f) => f.endsWith('.md') && f !== 'README.md')
  .sort()
sync(join(legalDir, 'README.md'), buildReadme(drafts), 'docs/legal/README.md (marker register)')

if (check && stale) process.exit(1)
if (!stale) console.log('[legal] generated legal texts and the marker register are up to date')
